import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { categoryColours, dark, fontStacks, light, radius, spacing } from '../src/index.ts';
import type { Palette } from '../src/index.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kebab = (s: string): string => s.replace(/[A-Z0-9]/g, (m) => `-${m.toLowerCase()}`);
type Mode = 'light' | 'dark';

const paletteVars = (p: Palette, mode: Mode): string => {
  const lines = Object.entries(p).map(([k, v]) => `  --${kebab(k)}: ${v};`);
  for (const [slug, c] of Object.entries(categoryColours)) lines.push(`  --c-${slug}: ${c[mode]};`);
  // shadcn semantic theme, mapped from Finally tokens
  const shadcn: Record<string, string> = {
    background: p.paper,
    foreground: p.ink,
    card: p.surface,
    'card-foreground': p.ink,
    popover: p.surface,
    'popover-foreground': p.ink,
    primary: p.brand,
    'primary-foreground': p.brandInk,
    secondary: p.raised,
    'secondary-foreground': p.ink,
    muted: p.raised,
    'muted-foreground': p.ink2,
    accent: p.brandSoft,
    'accent-foreground': p.brand,
    destructive: p.bad,
    border: p.rule,
    input: p.rule,
    ring: p.brand,
    'chart-1': categoryColours.groceries[mode],
    'chart-2': categoryColours.rent[mode],
    'chart-3': categoryColours['eating-out'][mode],
    'chart-4': categoryColours.bills[mode],
    'chart-5': categoryColours.transport[mode],
  };
  for (const [k, v] of Object.entries(shadcn)) lines.push(`  --${k}: ${v};`);
  lines.push(`  color-scheme: ${mode};`);
  return lines.join('\n');
};

const css = `/* GENERATED by packages/tokens - do not edit. */
:root {
${paletteVars(light, 'light')}
  --radius: ${radius.card}px;
  --radius-control: ${radius.control}px;
  --radius-card: ${radius.card}px;
  --radius-chip: ${radius.chip}px;
  --f-display: ${fontStacks.display};
  --f-body: ${fontStacks.body};
  --f-mono: ${fontStacks.mono};
${Object.entries(spacing)
  .map(([k, v]) => `  --space-${k}: ${v}px;`)
  .join('\n')}
}
:root[data-theme='dark'] {
${paletteVars(dark, 'dark')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${paletteVars(dark, 'dark').replace(/^/gm, '  ')}
  }
}
`;

mkdirSync(join(root, 'css'), { recursive: true });
mkdirSync(join(root, 'preset'), { recursive: true });
writeFileSync(join(root, 'css', 'theme.css'), css);

// NativeWind (Tailwind 3) preset. Colours read RGB channel variables set by the app theme provider.
const colourMap: Record<string, string> = {
  ...Object.fromEntries(
    Object.keys(light).map((k) => [kebab(k), `rgb(var(--m-${kebab(k)}) / <alpha-value>)`]),
  ),
  ...Object.fromEntries(
    Object.keys(categoryColours).map((k) => [`c-${k}`, `rgb(var(--m-c-${k}) / <alpha-value>)`]),
  ),
};
const preset = `/* GENERATED by packages/tokens - do not edit. */
module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(colourMap, null, 2)},
      borderRadius: { control: '${radius.control}px', card: '${radius.card}px', chip: '${radius.chip}px' },
      fontFamily: {
        display: ['BricolageGrotesque_700Bold'],
        'display-semi': ['BricolageGrotesque_600SemiBold'],
        body: ['HankenGrotesk_400Regular'],
        'body-medium': ['HankenGrotesk_500Medium'],
        'body-semi': ['HankenGrotesk_600SemiBold'],
        mono: ['IBMPlexMono_400Regular'],
        'mono-medium': ['IBMPlexMono_500Medium'],
      },
    },
  },
};
`;
writeFileSync(join(root, 'preset', 'nativewind-preset.cjs'), preset);

const hexToRgb = (hex: string): string => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};
const channels = (p: Palette, mode: Mode): Record<string, string> => ({
  ...Object.fromEntries(Object.entries(p).map(([k, v]) => [`--m-${kebab(k)}`, hexToRgb(v)])),
  ...Object.fromEntries(
    Object.entries(categoryColours).map(([slug, c]) => [`--m-c-${slug}`, hexToRgb(c[mode])]),
  ),
});
writeFileSync(
  join(root, 'src', 'native-themes.ts'),
  `// GENERATED by scripts/generate.ts - do not edit.\nexport const nativeThemes: Record<'light' | 'dark', Record<string, string>> = ${JSON.stringify(
    { light: channels(light, 'light'), dark: channels(dark, 'dark') },
    null,
    2,
  )};\n`,
);
